def public_case(case_id, game=None):
    game = game or build_game()
    if case_id not in game["players"]:
        raise KeyError(case_id)
    return json.loads(json.dumps(game["players"][case_id]))


def score_case(case_id, selections, elapsed_seconds, game=None):
    game = game or build_game()
    if case_id not in game["players"]:
        raise KeyError(case_id)
    if not isinstance(selections, list) or any(not isinstance(item, str) for item in selections) or len(selections) != len(set(selections)):
        raise ValueError("Selections must be a unique string list")
    if type(elapsed_seconds) is not int or not 0 <= elapsed_seconds <= 86400:
        raise ValueError("Invalid elapsed time")
    case, answer = game["players"][case_id], game["answers"][case_id]
    candidates = {item["id"]: item for item in case["candidates"]}
    if any(item not in candidates for item in selections):
        raise ValueError("Unknown candidate")
    targets, chosen = set(answer["target_ids"]), set(selections)
    true_ids, false_ids, missed = sorted(chosen & targets), sorted(chosen - targets), sorted(targets - chosen)
    evidence_points = sum(answer['candidate_points'][item] for item in true_ids)
    completion = answer["completeness_bonus"] if not missed else 0
    limit = case["time_limit_minutes"] * 60
    speed = round(answer["maximum_speed_bonus"] * max(0, limit - elapsed_seconds) / limit) if true_ids else 0
    points = max(0, evidence_points + completion + speed - answer["false_positive_penalty"] * len(false_ids))
    max_points = sum(answer['candidate_points'][item] for item in targets) + answer["completeness_bonus"] + answer["maximum_speed_bonus"]
    return dict(case_id=case_id, points=points, max_points=max_points, true_positives=len(true_ids), false_positives=len(false_ids),
                false_negatives=len(missed), correct=true_ids, unsupported=false_ids, missed=missed, speed_bonus=speed,
                rationale=answer["rationale"], exposure=answer["exposure"], severity=answer["severity"], course_path=case["course_path"],
                caution="The result scores this deterministic fictional case only. It does not estimate real-world fraud probability or criminality.")


def _json(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def _csv(rows):
    output = io.StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=list(rows[0]))
    writer.writeheader(); writer.writerows(rows)
    return output.getvalue().replace("\r\n", "\n").encode()


def _case_markdown(case):
    lines = [f"# {case['title']}", "", "**FICTIONAL PLAYER CASE — keep the facilitator key separate.**", "", case["brief"], "", "## Inbox", ""]
    lines += [f"- {item}" for item in case["reference"]]
    lines += ["", "## One-page ledger", "", "| ID | Date | Party | Amount / quantity | Group | Note |", "| --- | --- | --- | ---: | --- | --- |"]
    lines += [f"| {row['record_id']} | {row['date']} | {row['party']} | {row['amount_or_quantity']:,} | {row['review_group']} | {row['note']} |" for row in case["ledger"]]
    lines += ["", "## Submit one or more scoped findings", ""] + [f"- [ ] `{item['id']}` — {item['label']}" for item in case["candidates"]]
    lines += ["", f"Time limit: {case['time_limit_minutes']} minutes. Extension: {case['course_path']}. Do not identify a person or crime from this packet.", ""]
    return "\n".join(lines).encode()


def artifacts():
    game = build_game()
    files = {"game/v1/catalog.json": _json(game["catalog"]), "game/v1/instructor/answers.json": _json(game["answers"])}
    for case_id, case in game["players"].items():
        files[f"game/v1/player/{case_id}.json"] = _json(case)
        files[f"game/v1/ledgers/{case_id}.csv"] = _csv(case["ledger"])
        files[f"game/v1/print/{case_id}.md"] = _case_markdown(case)
    rules = """# Case-file game rules

Every case is fictional. Choose **cooperative** play for one shared answer or **competitive** play for separate timed submissions.

1. Keep `instructor/answers.json` away from players.
2. Give each player or team the case page, its one-page ledger, and a score sheet.
3. Start the timer. Players may calculate, filter, or mark paper; the basic game requires no code.
4. Submit scoped candidate IDs. Never name an individual as a criminal.
5. Score target candidate points from the facilitator key, add 20 for complete target coverage, add up to 20 for time only when at least one target is found, and subtract 15 for each unsupported candidate. Scores never represent damages, guilt, or fraud probability.
6. Read the rationale and required next evidence. For the analyst version, continue at the linked course lesson with Python, R, or Power BI.

Cooperative option: discuss one submission and record the evidence request. Competitive option: submit independently; highest points wins, with fewer unsupported candidates as the tie-breaker.
"""
    files["game/v1/rules.md"] = rules.encode()
    files["game/v1/score-sheet.csv"] = b"player_or_team,mode,case_id,selections,elapsed_seconds,points,false_positives,evidence_request\n"
    manifest_rows = [{"path": path, "sha256": hashlib.sha256(payload).hexdigest(), "bytes": len(payload)} for path, payload in sorted(files.items())]
    files["game/v1/manifest.json"] = _json(dict(version=VERSION, fictional=True, artifacts=manifest_rows))
    return files


def build():
    for relative, payload in artifacts().items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)


def verify():
    expected = artifacts()
    for relative, payload in expected.items():
        path = ROOT / relative
        if not path.exists() or path.read_bytes() != payload:
            raise ValueError("Game artifact mismatch: " + relative)
    return dict(valid=True, cases=4, artifacts=len(expected), version=VERSION)


